/**
 * Generates docs/META-TEMPLATES.md from the template list in prisma/seed.ts (the single source of
 * truth): `pnpm templates:doc`. tests/unit/templates.test.ts fails when the doc is out of date.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { TEMPLATES, type TemplateSeed } from "../prisma/seed";

const fill = (t: TemplateSeed) => t.body.replace(/\{\{(\d+)\}\}/g, (_m, n: string) => t.samples[Number(n) - 1] ?? "");
const cell = (s: string) => s.replace(/\|/g, "\\|");

export function renderMetaTemplates(templates: readonly TemplateSeed[] = TEMPLATES): string {
  const out: string[] = [
    "# WhatsApp templates to submit to Meta",
    "",
    "<!-- GENERATED by `pnpm templates:doc` from prisma/seed.ts. Do not edit by hand: change the seed and regenerate. -->",
    "",
    "Submit each template below in **WhatsApp Manager → Message templates → Create template**, exactly as written:",
    "",
    "- **Name**, **category** and **language** as given (names are used verbatim in code).",
    "- **Body**: paste it as is. The `{{n}}` placeholders are the variables, in order.",
    "- **Sample values**: Meta asks for one per variable; use the ones listed.",
    "- No header, footer or buttons: links are part of the body text.",
    "",
    "After Meta approves them, run `pnpm seed:prod --approve-templates` on the server (see README → Deploy) so the app starts sending them. Until a template is APPROVED, the app skips it and tells staff why.",
    "",
    `## Summary (${templates.length} templates)`,
    "",
    "| Name | Category | Language | Purpose | Variables |",
    "|---|---|---|---|---|",
    ...templates.map((t) => `| \`${t.name}\` | ${t.category} | ${t.language} | ${t.purpose} | ${t.variables.map((v, i) => `{{${i + 1}}} ${v}`).join(", ")} |`),
    "",
  ];
  for (const t of templates) {
    out.push(
      `## \`${t.name}\``,
      "",
      `- **Category:** ${t.category}${t.category === "MARKETING" ? " (sent only to customers who opted in to marketing)" : ""}`,
      `- **Language:** ${t.language}`,
      `- **Used for:** ${t.usedFor}`,
      "",
      "**Body**",
      "",
      "```text",
      t.body,
      "```",
      "",
      "| Variable | Meaning | Sample value |",
      "|---|---|---|",
      ...t.variables.map((v, i) => `| {{${i + 1}}} | ${cell(v)} | ${cell(t.samples[i] ?? "")} |`),
      "",
      `**Preview with samples:** ${fill(t)}`,
      "",
    );
  }
  return out.join("\n");
}

export const META_TEMPLATES_PATH = path.resolve(import.meta.dirname, "../docs/META-TEMPLATES.md");

if (path.basename(process.argv[1] ?? "") === "gen-meta-templates.ts") {
  writeFileSync(META_TEMPLATES_PATH, renderMetaTemplates());
  console.log(`wrote ${path.relative(process.cwd(), META_TEMPLATES_PATH)} (${TEMPLATES.length} templates)`);
}
